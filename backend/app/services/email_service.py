import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Tuple, Optional

# -----------------------------------------------------------------------------
# SMTP Configuration (Environment variables only)
# -----------------------------------------------------------------------------
def get_smtp_host() -> Optional[str]:
    host = os.getenv("SMTP_HOST")
    if not host or "your_smtp" in host or "example.com" in host or host.strip() == "":
        return None
    return host.strip()

def get_smtp_port() -> int:
    try:
        return int(os.getenv("SMTP_PORT", "587"))
    except ValueError:
        return 587

def get_smtp_user() -> Optional[str]:
    return os.getenv("SMTP_USER")

def get_smtp_password() -> Optional[str]:
    return os.getenv("SMTP_PASSWORD")

def get_from_email() -> str:
    return os.getenv("FROM_EMAIL") or os.getenv("SMTP_FROM_EMAIL", "notifications@calibtrack.com")

def get_smtp_timeout() -> int:
    try:
        return int(os.getenv("SMTP_TIMEOUT_SECONDS", "10"))
    except ValueError:
        return 10

def is_smtp_configured() -> bool:
    """
    Returns True if an active SMTP host is configured.
    """
    return get_smtp_host() is not None

# -----------------------------------------------------------------------------
# Email Dispatcher
# -----------------------------------------------------------------------------
def send_calibration_reminder_email(
    recipient_email: str,
    equipment_code: str,
    equipment_name: str,
    department: str,
    due_date: str,
    days_remaining: int,
    is_overdue: bool
) -> Tuple[bool, Optional[str]]:
    """
    Sends a calibration alert email using standard SMTP.
    If SMTP is unconfigured, skips gracefully without interrupting in-app notifications.
    Security: Never logs passwords or credentials.
    """
    if not is_smtp_configured():
        msg = (
            "SMTP is not configured in backend environment variables (SMTP_HOST is not set). "
            "To enable live email dispatch, configure SMTP_HOST, SMTP_PORT, SMTP_USER, "
            "SMTP_PASSWORD, and FROM_EMAIL in backend/.env."
        )
        return False, msg

    host = get_smtp_host()
    port = get_smtp_port()
    user = get_smtp_user()
    password = get_smtp_password()
    from_addr = get_from_email()
    timeout = get_smtp_timeout()

    # Build MIME Message
    status_label = "OVERDUE" if is_overdue else "DUE SOON"
    subject = f"[CalibTrack Metrology Alert] Calibration {status_label}: {equipment_name} ({equipment_code})"

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = from_addr
    msg["To"] = recipient_email

    # Plain-text version
    text_content = f"""
CALIBTRACK LABORATORY METROLOGY ALERT
======================================
Status: {status_label}
Equipment: {equipment_name}
Asset Code: {equipment_code}
Department: {department}
Calibration Due Date: {due_date}
{f'Overdue By: {abs(days_remaining)} days' if is_overdue else f'Days Remaining: {days_remaining} days'}

This is an automated calibration notification generated by CalibTrack.
Please schedule calibration verification with an accredited metrology provider.
    """.strip()

    # HTML version
    html_content = f"""
    <!DOCTYPE html>
    <html>
    <head><meta charset="utf-8"></head>
    <body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; line-height: 1.5; color: #1e293b; background-color: #f8fafc; padding: 20px;">
      <div style="max-width: 580px; margin: 0 auto; background-color: #ffffff; border: 1px solid #e2e8f0; border-radius: 12px; overflow: hidden;">
        <div style="background-color: {'#dc2626' if is_overdue else '#2563eb'}; padding: 18px 24px; color: #ffffff;">
          <h2 style="margin: 0; font-size: 18px; font-weight: 600;">CalibTrack Metrology Notification</h2>
          <p style="margin: 4px 0 0; font-size: 13px; opacity: 0.9;">Calibration Status: {status_label}</p>
        </div>
        <div style="padding: 24px;">
          <p style="margin-top: 0;">An instrument assigned to your department requires metrological calibration attention:</p>
          <table style="width: 100%; border-collapse: collapse; margin: 16px 0; font-size: 14px;">
            <tr><td style="padding: 8px 0; color: #64748b; width: 140px;">Instrument:</td><td style="font-weight: 600;">{equipment_name}</td></tr>
            <tr><td style="padding: 8px 0; color: #64748b;">Asset Code:</td><td style="font-mono font-weight: 600;">{equipment_code}</td></tr>
            <tr><td style="padding: 8px 0; color: #64748b;">Department:</td><td>{department}</td></tr>
            <tr><td style="padding: 8px 0; color: #64748b;">Due Date:</td><td><strong>{due_date}</strong></td></tr>
            <tr><td style="padding: 8px 0; color: #64748b;">Compliance:</td><td style="color: {'#dc2626' if is_overdue else '#d97706'}; font-weight: 600;">{f'Overdue by {abs(days_remaining)} days' if is_overdue else f'{days_remaining} days remaining'}</td></tr>
          </table>
          <p style="font-size: 13px; color: #64748b; margin-bottom: 0;">Please ensure calibration verification conforms to laboratory ISO 17025 standard operating procedures.</p>
        </div>
      </div>
    </body>
    </html>
    """.strip()

    msg.attach(MIMEText(text_content, "plain"))
    msg.attach(MIMEText(html_content, "html"))

    try:
        server = smtplib.SMTP(host=host, port=port, timeout=timeout)
        try:
            # Start TLS if port 587 or server supports it
            if port == 587:
                server.starttls()
            if user and password:
                server.login(user, password)
            server.sendmail(from_addr, [recipient_email], msg.as_string())
            return True, None
        finally:
            server.quit()
    except Exception as e:
        # Sanitized error logging: NEVER prints credentials
        error_name = type(e).__name__
        print(f"[Email Dispatch Error] Failed to send email to recipient: {error_name}")
        return False, f"SMTP failure ({error_name})"


